# ==========================================================
# PROMPT
# ==========================================================

def build_prompt(target_attribute):
    prompt = """
    You are evaluating a base image and a counterfactual image.

    The counterfactual image was generated by an image editing model. Small rendering artifacts, negligible lighting differences, or minor texture variations are expected and should not be considered failures unless they are visually significant.

    The intended edited attribute belongs to one of the following non-identity attribute categories:

    • Skin Tone (3 classes)
    • Facial Expression (4 classes)
    • Hair Styles (Male) (7 classes)
    • Hair Styles (Female) (6 classes)
    • Cultural Markers (Male) (6 classes)
    • Cultural Markers (Female) (6 classes)
    • Facial Hair (Non-Child Male) (5 classes)
    • Tattoos (2 classes)
    • Piercings (2 classes)

    The target attribute provided with the image pair specifies the intended edit within one of these categories.

    Evaluate the image pair from the perspective of a reasonable human observer. Ignore insignificant pixel-level differences, minor rendering artifacts, slight lighting changes, or negligible texture differences that naturally occur during image generation.

    Evaluate the counterfactual image using the following four criteria.

    Q1: Target Attribute Visibility

    Is the target non-identity attribute (e.g., face tattoo, hijab, fade haircut) clearly present and identifiable in the counterfactual image?

    Q2: Target Attribute Isolation

    Is the target attribute the only visual feature modified while all other attributes remain unchanged?

    Q3: Identity Preservation

    Does the underlying biometric identity (race, gender, age) remain perfectly consistent between the base image and the counterfactual?

    Q4: Environmental Consistency

    Is the counterfactual free of unintended generative hallucinations, lighting shifts, or background distortions?

    Evaluation Guidelines

    • Consider only visually meaningful semantic changes.
    • Ignore tiny rendering imperfections that do not alter the semantic content of the image.
    • For Q2, ignore insignificant pixel-level differences, but assign 0 if another meaningful semantic attribute has changed (for example hairstyle, facial expression, facial hair, clothing, accessories, skin tone beyond the intended edit, pose, facial geometry, etc.).
    • For Q3, assign 1 if a human observer would clearly recognize the same individual despite minor image generation artifacts.
    • For Q4, assign 0 only for noticeable artifacts, hallucinations, duplicated or missing objects, obvious lighting inconsistencies, or background distortions.

    Scoring

    1 = Yes
    0 = No

    Use score 1 whenever the criterion is clearly satisfied from a human visual perspective.
    Use score 0 only when there is a clear and noticeable violation of the criterion.

    Return ONLY valid JSON.

    {
      "Q1": {
        "score": 0,
        "reason": "..."
      },
      "Q2": {
        "score": 0,
        "reason": "..."
      },
      "Q3": {
        "score": 0,
        "reason": "..."
      },
      "Q4": {
        "score": 0,
        "reason": "..."
      }
    }

    Rules:
    - Return valid JSON only.
    - Do not include markdown.
    - Do not include explanations outside the JSON.
    - Scores must be either 0 or 1.
    """

    return (
        f"Target Attribute: {target_attribute}\n\n"
        + prompt
    )

# ==========================================================
# IMAGE -> BASE64
# ==========================================================

def image_to_base64(image_path):

    with open(image_path, "rb") as f:

        encoded = base64.b64encode(
            f.read()
        ).decode("utf-8")

    return encoded


# ==========================================================
# ATTRIBUTE EXTRACTION
# ==========================================================

def get_target_attribute(
    base_file,
    variation_file
):

    base_name = os.path.splitext(
        base_file
    )[0]

    variation_name = os.path.splitext(
        variation_file
    )[0]

    return variation_name[
        len(base_name) + 1:
    ]


# ==========================================================
# MATCHING
# ==========================================================

def find_variations(
    base_file,
    variation_dir
):

    prefix = os.path.splitext(
        base_file
    )[0]

    matches = []

    for file in os.listdir(
        variation_dir
    ):

        if file.startswith(
            prefix + "_"
        ):

            matches.append(file)

    return matches


# ==========================================================
# JSON PARSER
# ==========================================================

def parse_json(text):

    text = text.strip()

    try:
        return json.loads(text)

    except:

        start = text.find("{")
        end = text.rfind("}")

        if start != -1 and end != -1:

            candidate = text[start:end+1]

            return json.loads(candidate)

    raise ValueError(
        "Could not parse JSON response"
    )


# ==========================================================
# OPENROUTER CALL
# ==========================================================

def evaluate_pair(
    base_path,
    variation_path,
    target_attribute
):

    base64_base = image_to_base64(
        base_path
    )

    base64_cf = image_to_base64(
        variation_path
    )

    payload = {

        "model": MODEL,

        "temperature": 0,

        "messages": [

            {
                "role": "user",

                "content": [

                    {
                        "type": "text",
                        "text": build_prompt(
                            target_attribute
                        )
                    },

                    {
                        "type": "image_url",
                        "image_url": {
                            "url":
                            f"data:image/png;base64,{base64_base}"
                        }
                    },

                    {
                        "type": "image_url",
                        "image_url": {
                            "url":
                            f"data:image/png;base64,{base64_cf}"
                        }
                    }
                ]
            }
        ]
    }

    headers = {

        "Authorization":
        f"Bearer {OPENROUTER_API_KEY}",

        "Content-Type":
        "application/json"
    }

    for attempt in range(
        MAX_RETRIES
    ):

        try:

            response = requests.post(
                "https://openrouter.ai/api/v1/chat/completions",
                headers=headers,
                json=payload,
                timeout=300
            )

            response.raise_for_status()

            data = response.json()

            content = data[
                "choices"
            ][0][
                "message"
            ][
                "content"
            ]

            return parse_json(
                content
            )

        except Exception as e:

            print(
                f"Retry {attempt+1}: {e}"
            )

            time.sleep(5)

    raise RuntimeError(
        "Max retries exceeded"
    )


# ==========================================================
# RESUME SUPPORT
# ==========================================================

processed_pairs = set()

if os.path.exists(
    OUTPUT_CSV
):

    old_df = pd.read_csv(
        OUTPUT_CSV
    )

    for _, row in old_df.iterrows():

        processed_pairs.add(

            (
                row["base_image"],
                row["counterfactual_image"]
            )
        )

print(
    f"Already processed: "
    f"{len(processed_pairs)}"
)

# ==========================================================
# BUILD PAIRS
# ==========================================================

all_pairs = []

for base_file in os.listdir(
    BASE_DIR
):

    if not base_file.lower().endswith(
        ".png"
    ):
        continue

    variations = find_variations(
        base_file,
        VARIATION_DIR
    )

    for variation_file in variations:

        all_pairs.append(

            (
                base_file,
                variation_file
            )
        )

print(
    f"Total pairs found: "
    f"{len(all_pairs)}"
)

# ==========================================================
# PROCESS
# ==========================================================

for (
    base_file,
    variation_file

) in tqdm(
    all_pairs,
    desc="Evaluating"
):

    pair_key = (
        base_file,
        variation_file
    )

    if pair_key in processed_pairs:
        continue

    base_path = os.path.join(
        BASE_DIR,
        base_file
    )

    variation_path = os.path.join(
        VARIATION_DIR,
        variation_file
    )

    attribute = (
        get_target_attribute(
            base_file,
            variation_file
        )
    )

    output = {

        "base_image":
        base_file,

        "counterfactual_image":
        variation_file,

        "target_attribute":
        attribute
    }

    try:

        result = evaluate_pair(
            base_path,
            variation_path,
            attribute
        )

        output["Q1"] = int(
            result["Q1"]["score"]
        )

        output["Q2"] = int(
            result["Q2"]["score"]
        )

        output["Q3"] = int(
            result["Q3"]["score"]
        )

        output["Q4"] = int(
            result["Q4"]["score"]
        )

        output["Q1_reason"] = (
            result["Q1"]["reason"]
        )

        output["Q2_reason"] = (
            result["Q2"]["reason"]
        )

        output["Q3_reason"] = (
            result["Q3"]["reason"]
        )

        output["Q4_reason"] = (
            result["Q4"]["reason"]
        )

        output["error"] = ""

    except Exception as e:

        output["Q1"] = -1
        output["Q2"] = -1
        output["Q3"] = -1
        output["Q4"] = -1

        output["Q1_reason"] = ""
        output["Q2_reason"] = ""
        output["Q3_reason"] = ""
        output["Q4_reason"] = ""

        output["error"] = str(e)

    pd.DataFrame(
        [output]
    ).to_csv(

        OUTPUT_CSV,

        mode="a",

        header=not os.path.exists(
            OUTPUT_CSV
        ),

        index=False
    )

    time.sleep(
        SLEEP_SECONDS
    )

print(
    "\nFinished."
)


